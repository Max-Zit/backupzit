// percentText is the percentage on the progress page. A no-break space
// keeps "%" with the number: the label wraps at a space and showed only
// "100" when it was a little too narrow (#61).
func percentText(done, total uint64) string {
	p := uint64(100)
	if total > 0 {
		p = min(done*100/total, 100)
	}
	return fmt.Sprintf("%d\u00a0%%", p)
}

// span is a partition on disk in bytes.
type span struct{ off, len uint64 }

// pix is the bar of a partition in pixels.
type pix struct{ x, w int }

// barSpans places partition bars in width pixels: proportional to the
// disk, but each at least minW wide so small partitions (EFI, MSR) stay
// visible and labelled; the large ones give up the room. Free space keeps
// its proportional width.
func barSpans(parts []span, disk uint64, width, minW int) []pix {
	if disk == 0 || len(parts) == 0 {
		return nil
	}
	if n := len(parts); n*minW > width/2 {
		minW = max(1, width/(2*n))
	}
	scale := float64(width) / float64(disk)
	prop := make([]float64, len(parts))
	w := make([]float64, len(parts))
	var extra, slack float64
	for i, p := range parts {
		prop[i] = float64(p.len) * scale
		w[i] = max(prop[i], float64(minW))
		extra += w[i] - prop[i]
		if prop[i] > float64(minW) {
			slack += prop[i] - float64(minW)
		}
	}
	if extra > 0 && slack > 0 {
		f := min(1, extra/slack)
		for i := range w {
			if prop[i] > float64(minW) {
				w[i] -= (prop[i] - float64(minW)) * f
			}
		}
	}
	out := make([]pix, len(parts))
	var cursor float64
	var prevEnd uint64
	for i, p := range parts {
		if p.off > prevEnd {
			cursor += float64(p.off-prevEnd) * scale
		}
		out[i] = pix{x: int(cursor), w: int(w[i])}
		cursor += w[i]
		prevEnd = max(prevEnd, p.off+p.len)
	}
	return out
}

// chooseBackupDir picks the folder for the boot data saved before a
// repair: \backupzit on the first root that is not on the disk being
// repaired (avoid) and can be written (not the CD the recovery medium
// may be), else the temp folder.
func chooseBackupDir(roots []string, avoid map[string]bool, writable func(dir string) bool) string {
	for _, r := range roots {
		if avoid[r] {
			continue
		}
		d := filepath.Join(r, "backupzit")
		if fi, err := os.Stat(d); err == nil && fi.IsDir() && writable(d) {
			return d
		}
	}
	return os.TempDir()
}

// logText shows a progress line of the image functions (English, fixed
// beginnings) in the current language. The list of disk controller drivers
// is shortened to their number; unknown lines stay as they are.
func logText(s string) string {
	if rest, ok := strings.CutPrefix(s, "disk controller drivers set to start at boot: "); ok {
		n := len(strings.Fields(rest))
		return tf("Treiber für %d Disk-Controller beim Start aktiviert", "disk controller drivers enabled at start: %d", n)
	}
	// Lines of the restore job: prefixes around image lines, and its own.
	if rest, ok := strings.CutPrefix(s, "new hardware: "); ok {
		return t("Neue Hardware: ", "new hardware: ") + logText(rest)
	}
	if rest, ok := strings.CutPrefix(s, "warning: "); ok {
		return t("Hinweis: ", "warning: ") + warningText(rest)
	}
	switch s {
	case "verifying the snapshot":
		return t("Backup wird geprüft", "verifying the snapshot")
	case "snapshot verified":
		return t("Backup geprüft, keine Fehler", "snapshot verified")
	case "MBR boot code written":
		return t("Windows-Bootcode in den MBR geschrieben", "MBR boot code written")
	}
	var parts int
	var bytes uint64
	var dur string
	if _, err := fmt.Sscanf(s, "wrote %d partitions, %d bytes in %s", &parts, &bytes, &dur); err == nil {
		return tf("%d Partitionen geschrieben, %s in %s", "wrote %d partitions, %s in %s", parts, humanBytes(bytes), dur)
	}
	if rest, ok := strings.CutPrefix(s, "firmware "); ok {
		fw, files, found := strings.Cut(rest, ", boot files for ")
		if found {
			return tf("Firmware %s, Bootdateien für %s", "firmware %s, boot files for %s", firmwareText(fw), files)
		}
		return tf("Firmware %s", "firmware %s", firmwareText(rest))
	}
	if rest, ok := strings.CutPrefix(s, "boot data backed up to "); ok {
		return tf("Bootdaten gesichert nach %s", "boot data backed up to %s", rest)
	}
	if rest, ok := strings.CutPrefix(s, "boot files for "); ok {
		return tf("Bootdateien für %s", "boot files for %s", rest)
	}
	if rest, ok := strings.CutPrefix(s, "Windows found on "); ok {
		return tf("Windows gefunden auf %s", "Windows found on %s", rest)
	}
	if rest, ok := strings.CutPrefix(s, "adding drivers from "); ok {
		return tf("Treiber werden hinzugefügt aus %s", "adding drivers from %s", rest)
	}
	var n int
	if _, err := fmt.Sscanf(s, "partition %d is now active", &n); err == nil {
		return tf("Partition %d ist jetzt aktiv", "partition %d is now active", n)
	}
	return s
}

// problemText explains the problem pnputil reports for a device; a missing
// driver gets words, the raw code stays for support.
func problemText(p string) string {
	if strings.Contains(strings.ToUpper(p), "0XC0000490") || strings.Contains(p, "CM_PROB_FAILED_INSTALL") || strings.Contains(p, "(28)") {
		return t("kein passender Treiber geladen", "no matching driver loaded") + " (" + p + ")"
	}
	return p
}

