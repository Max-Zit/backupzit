// languages are the languages of the program: the 14 of the console
// (internal/server/i18n). German and English are written next to each
// other where a text is used (t("Deutsch", "English")), so the code still
// reads in both; the other twelve are in translations at the end of this
// file, looked up by the English text like the console's catalogs.
var languages = []string{"en", "cs", "de", "es", "fr", "it", "ja", "nl", "pl", "pt", "ru", "sr", "tr", "zh"}

// lang is the language of the texts, one of languages.
var lang = detectLang(os.Args[1:], os.Getenv("BACKUPZIT_LANG"), systemLang)

// detectLang picks the language: --lang=xx on the command line, then
// BACKUPZIT_LANG (startnet.cmd sets it from the -Language the medium was
// built with, so the program follows the build even when Windows PE has
// no language pack for it), then the display language of Windows (PE).
// It is English when the program has no texts in any of them.
func detectLang(args []string, env string, system func() string) string {
	for _, a := range args {
		if v, ok := strings.CutPrefix(a, "--lang="); ok {
			if l := normLang(v); l != "" {
				return l
			}
		}
	}
	if l := normLang(env); l != "" {
		return l
	}
	if l := normLang(system()); l != "" {
		return l
	}
	return "en"
}

// normLang turns a language tag such as "de-DE", "sr-Latn-RS", "pt_BR"
// or "zh" into one of languages, or "" when the program has no texts in
// that language (e.g. "hr-HR": English is the neutral choice there).
func normLang(tag string) string {
	base, _, _ := strings.Cut(strings.ReplaceAll(strings.ToLower(strings.TrimSpace(tag)), "_", "-"), "-")
	if slices.Contains(languages, base) {
		return base
	}
	return ""
}

// t picks the text in the current language: German and English from the
// call, the others from translations. A text without a translation stays
// English (TestEveryTextIsTranslated lists such texts).
func t(de, en string) string {
	switch lang {
	case "de":
		return de
	case "en":
		return en
	}
	if s := translations[lang][en]; s != "" {
		return s
	}
	return en
}

// tf is t with fmt.Sprintf. Translations keep the verbs of the English
// text in their order, or name the argument (%[2]s) where the sentence
// needs another order.
func tf(de, en string, args ...any) string { return fmt.Sprintf(t(de, en), args...) }

// decimalComma tells whether the current language writes 39,7 rather
// than 39.7.
func decimalComma() bool { return !slices.Contains([]string{"en", "ja", "zh"}, lang) }

// humanBytes formats a size in binary units, e.g. "39,7 GiB", the units
// of the size fields, so a size reads the same everywhere. The unit stays
// GiB in every language because the size fields say GiB.
func humanBytes(b uint64) string {
	const unit = 1024
	if b < unit {
		return fmt.Sprintf("%d B", b)
	}
	div, exp := uint64(unit), 0
	for n := b / unit; n >= unit; n /= unit {
		div *= unit
		exp++
	}
	s := fmt.Sprintf("%.1f %ciB", float64(b)/float64(div), "KMGTPE"[exp])
	if decimalComma() {
		s = strings.Replace(s, ".", ",", 1)
	}
	return s
}

// firmwareText shows imaging.Firmware.String() ("UEFI (Secure Boot on)",
// "BIOS", "unknown") in the current language.
func firmwareText(s string) string {
	return strings.NewReplacer(
		"Secure Boot on", t("Secure Boot an", "Secure Boot on"),
		"unknown", t("unbekannt", "unknown"),
	).Replace(s)
}

// reasonText says in the current language why a partition cannot be
// resized; kind is its type (imaging.Partition.Kind).
func reasonText(lim imaging.PartitionLimits, kind string) string {
	switch lim.Why {
	case imaging.ReasonNotBackedUp:
		return t("nicht gesichert", "not backed up")
	case imaging.ReasonFixedSize:
		return tf("Partitionen vom Typ „%s“ behalten ihre Größe", "%s partitions keep their size", kind)
	case imaging.ReasonBitLocker:
		return t("mit BitLocker verschlüsselt gesichert: nur verschiebbar, braucht nach dem Restore den Wiederherstellungsschlüssel",
			"backed up encrypted with BitLocker: can only be moved, needs its recovery key after the restore")
	case imaging.ReasonFileSystem:
		return t("Größenänderung nur für NTFS", "only NTFS is resized")
	case imaging.ReasonNotNTFS:
		return t("verschlüsselt (BitLocker) oder nicht als NTFS lesbar", "encrypted (BitLocker) or not readable as NTFS")
	case imaging.ReasonError:
		return t("nicht lesbar: ", "not readable: ") + lim.Reason
	case imaging.ReasonNoShrink:
		// The file system check's explanation stays as it is (English), as
		// for a read error: it names the cause and what to do.
		return t("nicht verkleinerbar: ", "cannot be shrunk: ") + strings.TrimPrefix(lim.Reason, imaging.NoShrinkPrefix)
	}
	return lim.Reason
}

// limitsInfo is the hint of a resizable partition p on the layout page: the
// space in use and the minimum, and why the minimum is that large when it
// is held up, e.g. by a copy that was not shut down cleanly (#61).
func limitsInfo(lim imaging.PartitionLimits, p *repo.PartitionImage) string {
	s := tf("belegt %s, mindestens %s", "used %s, at least %s", humanBytes(lim.UsedBytes), humanBytes(lim.Min(p)))
	if lim.Reason != "" {
		s += " – " + reasonText(lim, "")
	}
	return s
}

// heldText says why partition n keeps its size; kind is its type
// (imaging.Partition.Kind).
func heldText(n int, lim imaging.PartitionLimits, kind string) string {
	return tf("Partition %d: %s", "Partition %d: %s", n, reasonText(lim, kind))
}

// sizePair formats two sizes that are compared in one message; when they
// round to the same text, both are given in bytes.
func sizePair(a, b uint64) (string, string) {
	if x, y := humanBytes(a), humanBytes(b); x != y {
		return x, y
	}
	return fmt.Sprintf("%d B", a), fmt.Sprintf("%d B", b)
}

// layoutErrText shows an error of the layout planner in the current
// language: the "too small" errors with the reasons that hold partitions
// up (#61); other errors as they are.
func layoutErrText(err error) string {
	var ts *imaging.TooSmallError
	if errors.As(err, &ts) {
		disk, need := sizePair(ts.DiskSize, ts.Needed)
		s := tf("Die Zieldisk ist zu klein: %s, die Partitionen brauchen mindestens %s.", "The target disk is too small: %s, the partitions need at least %s.", disk, need)
		for _, h := range ts.Held {
			s += "\r\n" + heldText(h.Partition, h.Limits, "")
		}
		return s
	}
	var ms *imaging.MinSizeError
	if errors.As(err, &ms) {
		need, got := sizePair(ms.Min, ms.Length)
		s := tf("Partition %d braucht mindestens %s, das Layout gibt ihr %s.", "Partition %d needs at least %s, the layout gives it %s.", ms.Partition, need, got)
		if ms.Limits.Reason != "" {
			s += "\r\n" + heldText(ms.Partition, ms.Limits, "")
		}
		return s
	}
	return err.Error()
}

// warningText shows a warning of a restore (English, from the restore
// functions) in the current language when the program knows it; other
// warnings stay as they are.
func warningText(s string) string {
	if s == recovery.WarnShrunk {
		return t("Partitionen wurden verkleinert wiederhergestellt: Windows prüft ihre Dateisysteme (chkdsk) einmal beim nächsten Start",
			"partitions were restored smaller: Windows checks their file systems (chkdsk) once at the next start")
	}
	var part, disk int
	if _, err := fmt.Sscanf(s, imaging.SameIDOfflineWarning, &part, &disk); err == nil && fmt.Sprintf(imaging.SameIDOfflineWarning, part, disk) == s {
		return tf("Partition %d: nicht erweitert, weil Disk %d in diesem Computer dieselben Disk- und Partitions-IDs hat (die gesicherte Disk); Windows lässt diese Kopie deshalb offline. Die alte Disk entfernen und danach das Dateisystem in der Datenträgerverwaltung erweitern, sobald diese Disk online ist",
			"partition %d: not extended, because disk %d in this computer has the same disk and partition IDs (the backed up disk), so Windows keeps this copy offline; remove the old disk, then extend the file system in Disk Management once this disk is online", part, disk)
	}
	return s
}

